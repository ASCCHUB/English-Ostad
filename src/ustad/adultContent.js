export function adultWordTip(word){
 const note=adultSpellingNotes[word.en]||adultSpellingNotes[word.en.toLowerCase()];if(note)return note;
 const doubled=[...new Set([...word.en.toLowerCase().matchAll(/([a-z])\1/g)].map(m=>m[0]))];
 if(doubled.length)return `Notice ${doubled.join(' and ')}: keep both letters in each repeated pair. Cover ${word.en}, then recall the complete spelling.`;
 const ending=['tion','sion','ment','ness','able','ible','ance','ence','ing','ful','ous','ly'].find(s=>word.en.toLowerCase().endsWith(s));
 if(ending)return `Notice the final letters -${ending}. Study ${word.en.slice(0,-ending.length)} and ${ending} as spelling groups, then write the complete word.`;
 return `${word.en} has ${word.en.length} letters. Study the beginning and ending, then cover the word and recall the letters in order.`;
}
